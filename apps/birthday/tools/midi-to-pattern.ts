// Converts midi/happy-birthday.mid into src/happy-birthday.ts.
//
//     npm run pattern -w apps/birthday
//
// Run once whenever the MIDI file changes. The output is committed rather than
// produced at build time so the page ships notes, not a parser, and a test
// re-runs the conversion to catch the two drifting apart.

import { readFileSync, writeFileSync } from 'node:fs'
import { parseMidi } from '../src/midi.ts'
import { patternFrom } from '../src/pattern.ts'

const here = new URL('..', import.meta.url)
const pattern = patternFrom(parseMidi(readFileSync(new URL('midi/happy-birthday.mid', here))))

const notes = pattern.notes
  .map((note) => `    { step: ${note.step}, steps: ${note.steps}, midi: ${note.midi} },`)
  .join('\n')

writeFileSync(
  new URL('src/happy-birthday.ts', here),
  `// GENERATED by tools/midi-to-pattern.ts from midi/happy-birthday.mid — do not edit.
//
// "Happy Birthday to You", melody by Mildred J. Hill and Patty Hill (1893).
// MIDI: the flute setting from Breizh Partitions via celticscores.com
// (https://celticscores.com/sheet-music/790_Happy_Birthday_to_You),
// CC BY-SA 3.0 (https://creativecommons.org/licenses/by-sa/3.0/).

import type { Pattern } from './pattern.ts'

export const HAPPY_BIRTHDAY: Pattern = {
  stepMs: ${pattern.stepMs},
  stepsPerBeat: ${pattern.stepsPerBeat},
  stepsPerBar: ${pattern.stepsPerBar},
  loopSteps: ${pattern.loopSteps},
  tonic: ${pattern.tonic},
  minor: ${pattern.minor},
  notes: [
${notes}
  ],
}
`,
)

console.log(`${pattern.notes.length} notes, ${pattern.loopSteps / pattern.stepsPerBar} bars`)
